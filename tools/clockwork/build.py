"""Original open mechanical movement, with a continuous layered camera journey.

Reproduce: python3 tools/clockwork/build.py packs/clockwork
All teeth, rims, springs and bridges are ordinary bounded vector pack data.
"""
from pathlib import Path
import math
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pack_art import Art


def circle(radius, count=72, reverse=False):
    points = [(radius*math.cos(i*math.tau/count), radius*math.sin(i*math.tau/count)) for i in range(count)]
    return list(reversed(points)) if reverse else points


def ring(outer, inner):
    # A single winding contour returns along the opposite edge of the ring.
    # The centre really is open: the lower mechanism remains visible through it.
    a=circle(outer);b=circle(inner,reverse=True)
    return a+[a[0],b[0]]+b+[b[0],a[0]]


def tooth_outline(radius, count):
    points=[]
    # Shared module and conjugate pitch speeds keep meshing wheels coherent.
    for i in range(count):
        for offset,r in [(0,radius-.005),(.17,radius-.005),(.3,radius+.0045),
                         (.7,radius+.0045),(.83,radius-.005)]:
            theta=(i+offset)*math.tau/count
            points.append((r*math.cos(theta),r*math.sin(theta)))
    return points


def teeth(radius, count, inner):
    points=tooth_outline(radius,count)
    hole=circle(inner,reverse=True)
    return points+[points[0]]+hole+[hole[0],points[0]]


def layer(art, depth):
    art.draw('group',let=[f'plane_scale = lens / (1 - {depth} * approach)'],
             scale='plane_scale',x='-view_x * plane_scale',y='-view_y * plane_scale')


def screw(art,x,y,r=.012,depth=1,rotation=0):
    art.ellipse(x,y+.002,r*1.15,r*1.15,'alpha(black, 0.5)',depth,samples=32)
    art.ellipse(x,y,r,r,'edge',depth,samples=32)
    art.ellipse(x-.001,y-.001,r*.81,r*.81,'silver',depth,samples=32)
    art.draw('lines',depth,points=[[-r*.62,0],[r*.62,0]],x=x,y=y,rotate=rotation,
             width=.002,color='steel_dark')


def gear(art,x,y,teeth_count,angle,spokes=5,small=False):
    radius=teeth_count*.005
    art.draw('group',1,x=x,y=y)
    art.draw('group',2,rotate=angle)
    contour=teeth(radius,teeth_count,radius*.68)
    art.polygon(contour,'metal',3)
    art.draw('lines',3,points=tooth_outline(radius,teeth_count),closed=True,width=.0009,color='metal_light')
    art.draw('lines',3,points=circle(radius*.725),closed=True,width=.0022,color='metal_dark')
    art.draw('lines',3,points=circle(radius*.89),closed=True,width=.0009,color='alpha(metal_light, 0.65)')
    # Curved spokes leave generous windows down into the next plane.
    spoke=[(radius*.13,-radius*.075),(radius*.42,-radius*.1),(radius*.7,-radius*.045),
           (radius*.71,radius*.018),(radius*.45,-radius*.025),(radius*.13,radius*.065)]
    art.polygon(spoke,'metal',3,count=spokes,rotate=f'i * tau / {spokes}')
    art.draw('lines',3,count=spokes,points=[(radius*.18,-radius*.06),(radius*.43,-radius*.065),
                                           (radius*.69,-radius*.015)],rotate=f'i * tau / {spokes}',
             width=.001,color='metal_light')
    art.polygon(ring(radius*.17,radius*.065),'metal_light',3)
    art.polygon(ring(radius*.14,radius*.07),'metal_dark',3)
    art.ellipse(0,0,radius*.055,radius*.055,'silver',3,samples=24)
    # Every fourth tooth has an inset polished land; macro views reveal the marks.
    if not small:
        art.draw('lines',3,count=teeth_count//4,rotate=f'i * tau / {teeth_count//4}',
                 points=[(radius*.82,0),(radius*.865,0)],width=.001,color='metal_dark',visible='detail == 1')


