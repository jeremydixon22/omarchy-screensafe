    art.draw('rect',3,count=3,w=.237,h=.001,rotate='i * tau / 3',y=-.002,color='metal_light')
    art.draw('rect',3,count=12,x='0.144 * cos(i * tau / 12)',y='0.144 * sin(i * tau / 12)',
             w=.008,h=.004,rotate='i * tau / 12',color='silver')
    # The spring breathes without crossing its own coils.
    art.draw('lines',2,samples=480,
             px='(0.013 + s * 0.091) * cos(s * (tau * 9 + balance_angle))',
             py='(0.013 + s * 0.091) * sin(s * (tau * 9 + balance_angle))',
             width=.0011,color='finish == 2 ? cyan : #91b8c5')
    art.ellipse(0,0,.017,.017,'metal_dark',2,samples=32)
