    layer(art,0)
    art.ellipse(0,.025,.79,.455,'plate',1)
    art.draw('lines',1,points=[(.79*math.cos(i*math.tau/160),.455*math.sin(i*math.tau/160))
                              for i in range(160)],y=.025,closed=True,width=.004,color='plate_light')
    art.draw('lines',1,count=12,samples=64,
             px='(0.27 + i * 0.027) * cos(s * tau)',
             py='0.025 + (0.12 + i * 0.0195) * sin(s * tau)',
             width=.0007,color='alpha(plate_edge, 0.15)',visible='detail == 1')
    # A slow lower train can be seen through the open spokes of the upper gears.
    gear(art,-.41,.21,32,'-orbit * 3 + 0.04',spokes=4,small=True)
    gear(art,-.41+.28*math.cos(.45),.21+.28*math.sin(.45),24,'orbit * 4',spokes=4,small=True)
