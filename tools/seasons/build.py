"""Draw one original lakeside landscape in four seasons, entirely as pack data.

Reproduce with: python3 tools/seasons/build.py packs/seasons
No source photography, generated bitmap assets, fonts or external dependencies.
"""
from pathlib import Path
import math
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pack_art import Art


def build(destination):
    art = Art('''# Seasons: original vector landscape. Generated by tools/seasons/build.py.
format = 2
name = "Seasons"
author = "ScreenSafe"
license = "MIT"
description = "One quiet lakeside landscape through spring blossom, summer green, autumn gold and winter snow."
stage = "screen"
fps = 24
fade = 0
preview = 12
background = "#b6d6d6"
colorize = "tint_color"

[[setting]]
name = "season"
label = "Season"
kind = "choice"
choices = ["Spring", "Summer", "Fall", "Winter"]
values = [0, 1, 2, 3]
default = 0

[[setting]]
name = "breeze"
label = "Breeze"
kind = "choice"
choices = ["Still", "Gentle", "Fresh"]
values = [0, 0.5, 1]
default = 0.5

[[setting]]
name = "weather"
label = "Seasonal detail"
kind = "toggle"
default = true

[[setting]]
name = "tone"
label = "Tone"
kind = "choice"
choices = ["Natural", "Theme"]
values = [0, 1]
default = 0

[[setting]]
name = "tint_color"
label = "Color"
kind = "color"
default = 0
when = "tone"
when_value = 1

[colors]
sky_top = "tone == 1 ? mix(background, blue, 0.28) : pick(season, #a5c8cc, #83bfc7, #b7c4bf, #9baebf)"
sky_low = "tone == 1 ? mix(background, foreground, 0.22) : pick(season, #f1e5cf, #e6edc9, #f4debd, #e1e3df)"
sunlight = "tone == 1 ? mix(yellow, foreground, 0.55) : #fff0c9"
mist = "tone == 1 ? mix(background, foreground, 0.32) : pick(season, #c7d4cb, #b9d7cf, #d3cbb7, #c3ccd1)"
mountain = "tone == 1 ? mix(background, blue, 0.48) : pick(season, #6e9696, #638e90, #8c9790, #7e91a2)"
mount_shadow = "tone == 1 ? mix(background, blue, 0.3) : pick(season, #92aeaa, #80aaa6, #b2b29e, #9eafba)"
ridge = "tone == 1 ? mix(background, green, 0.38) : pick(season, #739b83, #477d6c, #9b9568, #a8b7b4)"
forest = "tone == 1 ? mix(background, green, 0.48) : pick(season, #537d73, #38675d, #6f785d, #617d83)"
water_top = "tone == 1 ? mix(background, cyan, 0.25) : pick(season, #94b8ae, #6daba3, #b6b497, #aabdc5)"
water_low = "tone == 1 ? mix(background, blue, 0.4) : pick(season, #466f74, #396e77, #677b74, #6a8797)"
bank = "tone == 1 ? mix(background, green, 0.28) : pick(season, #748461, #577447, #a48251, #d2d8d1)"
grass = "tone == 1 ? mix(background, green, 0.48) : pick(season, #819865, #5d8050, #b99451, #d8ddd6)"
grass_light = "tone == 1 ? mix(green, foreground, 0.35) : pick(season, #bed29a, #97b268, #dec07b, #f0eee2)"
wood = "tone == 1 ? mix(background, orange, 0.28) : pick(season, #645d51, #565947, #6e5643, #637078)"
wood_light = "tone == 1 ? mix(foreground, orange, 0.2) : pick(season, #a59577, #8b9371, #aa8665, #a8b5b5)"
leaf_dark = "tone == 1 ? mix(background, magenta, 0.45) : pick(season, #ba8190, #447450, #ab642e, #b8c5c6)"
leaf_mid = "tone == 1 ? mix(accent, foreground, 0.12) : pick(season, #e3abb1, #729955, #d6923e, #d7ded9)"
leaf_light = "tone == 1 ? mix(accent, foreground, 0.45) : pick(season, #f8d8cf, #b1bc70, #edbe68, #f2f1e9)"
roof = "tone == 1 ? mix(background, red, 0.48) : pick(season, #956f59, #8f6951, #8b5942, #bfcdd0)"
wall = "tone == 1 ? mix(background, foreground, 0.5) : pick(season, #e3d5b7, #d9d2ad, #e5cd9e, #d2d9d3)"

[[scene]]
name = "The lake"
duration = 32
background = "sky_top"
let = ["wind = breeze * sin(t * tau / 16)", "drift = 0.004 * sin(t * tau / 32)"]
''')
    # Generous overscan fills wide displays while the composition stays consistent.
    art.draw('group', scale='max(1, aspect / (16 / 9))', x='drift')
    art.draw('rect', 1, count=64, y='-0.5 + (i + 0.5) / 64', w=4, h=0.0161,
             color='mix(sky_top, sky_low, i / 63)')
    art.ellipse(.48, -.294, .061, .061, 'alpha(sunlight, 0.2)', 1)
    art.ellipse(.48, -.294, .043, .043, 'sunlight', 1)
    # Long, softly layered cloud banks: movement is a closed, unhurried orbit.
    for cx, cy, rx, ry in [(-.47, -.33, .18, .012), (.18, -.38, .14, .009), (.66, -.19, .21, .012)]:
        art.ellipse(f'{cx} + 0.015 * wind', cy, rx, ry, 'alpha(sky_low, 0.58)', 1)
        art.ellipse(f'{cx + .04} + 0.015 * wind', cy-.009, rx*.55, ry*1.3, 'alpha(sky_low, 0.42)', 1)
    far = [(-2, .09), (-2, -.04), (-.86, -.08), (-.73, -.18), (-.65, -.135), (-.46, -.33),
           (-.3, -.18), (-.21, -.22), (-.02, -.09), (.15, -.17), (.29, -.29), (.4, -.18),
           (.56, -.25), (.75, -.1), (1.1, -.16), (2, -.08), (2, .09)]
    art.polygon(far, 'mount_shadow', 1)
    art.polygon([(-.46, -.33), (-.4, -.245), (-.36, -.21), (-.42, -.225), (-.46, -.205),
                 (-.5, -.24), (-.55, -.22)], 'mix(mist, sky_low, 0.65)', 1)
    art.polygon([(.29, -.29), (.365, -.22), (.31, -.235), (.275, -.20), (.245, -.23)],
                'mix(mist, sky_low, 0.65)', 1)
    art.polygon([(-2,.14),(-2,-.04),(-.89,-.045),(-.66,-.13),(-.41,-.02),(-.13,-.075),
                 (.11,.01),(.34,-.09),(.57,-.02),(.79,-.12),(1.2,-.035),(2,-.08),(2,.14)], 'mountain', 1)
    art.polygon([(-2,.15),(-2,.035),(-.8,-.005),(-.54,.015),(-.32,.06),(-.14,.035),
                 (.08,.065),(.3,.02),(.54,.055),(.76,.01),(2,.045),(2,.15)], 'ridge', 1)
    # The evergreen forest and small far-bank houses establish scale.
    pine = [(0,-.04),(-.012,-.021),(-.007,-.022),(-.018,-.005),(-.012,-.007),(-.024,.012),(.024,.012),
            (.012,-.007),(.018,-.005),(.007,-.022),(.012,-.021)]
    art.polygon(pine, 'forest', 1, count=53, x='-1.2 + i * 0.046',
                y='0.065 + 0.012 * sin(i * 0.7)', scale='0.55 + 0.75 * hash(i + 16)')
    art.draw('rect', 1, x=.401, y=.064, w=.047, h=.034, color='wall')
    art.polygon([(.371,.05),(.397,.025),(.43,.047)], 'roof', 1)
    art.draw('rect', 1, x=.403, y=.069, w=.011, h=.019, color='wood')
    art.draw('rect', 1, x=.385, y=.064, w=.006, h=.007, color='sunlight')
    art.draw('rect', 1, x=.418, y=.064, w=.006, h=.007, color='sunlight')
    # Water: opaque bands below the horizon; narrow reflected sky paths undulate.
    art.draw('rect', 1, count=52, y='0.098 + (i + 0.5) * 0.008', w=4, h=.0082,
             color='mix(water_top, water_low, i / 51)')
    art.draw('rect', 1, count=64, x='0.44 + 0.02 * sin(i * 2.4 + t * tau / 16)',
             y='0.104 + i * 0.0058', w='0.015 + i * 0.0019 + 0.024 * hash(i * 3.7)', h=.0012,
             color='alpha(sunlight, 0.04 + 0.09 * hash(i * 2.8))')
    art.draw('lines', 1, count=32, samples=18, x='-1 + 2 * hash(i * 8.8)',
             y='0.12 + 0.35 * hash(i * 1.4)',
             px='s * (0.04 + 0.1 * hash(i * 2))', py='0.0009 * sin(s * tau + t * tau / 16 + i)',
             width=.0008, color='alpha(sky_low, 0.08 + 0.1 * hash(i * 7.1))')
    # Fixed shoreline, then the foreground promontory with winding footpath.
    art.polygon([(-2,.52),(-2,.13),(-.82,.14),(-.69,.16),(-.57,.19),(-.44,.23),(-.4,.29),
                 (-.3,.32),(-.18,.34),(-.1,.38),(-.15,.44),(-.11,.52)], 'bank', 1)
    art.polygon([(-2,.52),(-2,.17),(-.82,.18),(-.66,.20),(-.54,.225),(-.48,.27),(-.4,.31),
                 (-.34,.35),(-.19,.38),(-.15,.43),(-.22,.52)], 'grass', 1)
    art.polygon([(-.74,.49),(-.61,.42),(-.52,.37),(-.44,.33),(-.39,.29),(-.41,.273),
                 (-.46,.316),(-.54,.35),(-.65,.385),(-.82,.445)], 'mix(grass_light, wall, 0.55)', 1)
    # Broad roots and trunk are identical in every season; foliage reveals them in winter.
    trunk = [(-.66,.30),(-.61,.27),(-.591,.12),(-.605,-.025),(-.644,-.13),(-.625,-.125),
             (-.579,-.04),(-.56,-.16),(-.531,-.23),(-.538,-.13),(-.566,.015),(-.54,.07),
             (-.472,-.02),(-.42,-.06),(-.449,-.006),(-.52,.11),(-.553,.16),(-.557,.27),(-.51,.31)]
    art.polygon(trunk, 'wood', 1)
    art.draw('lines', 1, points=[(-.615,.27),(-.584,.105),(-.582,.02),(-.546,-.145)],
             width=.003, color='alpha(wood_light, 0.48)')
    for pts in [[(-.594,.033),(-.69,-.04),(-.75,-.16)], [(-.632,-.068),(-.72,-.13),(-.80,-.14)],
                [(-.56,-.06),(-.48,-.11),(-.44,-.18)], [(-.53,.045),(-.415,.02),(-.35,-.045)],
                [(-.69,-.04),(-.77,-.05),(-.82,-.11)], [(-.48,-.11),(-.395,-.125)]]:
        art.draw('lines', 1, points=pts, width=.006, color='wood')
    # Slightly irregular overlapping leaf masses, each attached to the same tree.
    clusters = [(-.77,-.16,.095,.07),(-.68,-.19,.105,.08),(-.58,-.23,.105,.08),
                (-.49,-.21,.09,.07),(-.42,-.15,.10,.075),(-.74,-.07,.12,.07),
                (-.61,-.105,.12,.085),(-.49,-.07,.13,.075),(-.39,-.065,.085,.055)]
    for k,(x,y,rx,ry) in enumerate(clusters):
        contour=[]
        for j in range(60):
            a=j*math.tau/60;radius=1+.065*math.sin(a*9+k)+.035*math.sin(a*13)
            contour.append((rx*radius*math.cos(a),ry*radius*math.sin(a)))
        art.polygon(contour, 'leaf_dark', 1, x=f'{x} + 0.004 * wind', y=y, visible='season != 3')
        art.polygon([(px*.88,py*.80) for px,py in contour], 'leaf_mid', 1,
                    x=f'{x-.009} + 0.004 * wind', y=y-.014, visible='season != 3')
        art.polygon([(px*.59,py*.36) for px,py in contour], 'alpha(leaf_light, 0.48)', 1,
                    x=f'{x-.015} + 0.004 * wind', y=y-.033, visible='season != 3')
    # Winter snow rests on the branches, rather than substituting another tree.
    for pts in [[(-.77,-.052),(-.69,-.042),(-.642,-.005)], [(-.56,-.065),(-.48,-.115),(-.395,-.13)],
                [(-.53,.041),(-.415,.016),(-.35,-.05)], [(-.605,-.026),(-.64,-.125)]]:
        art.draw('lines',1,points=pts,width=.009,color='leaf_light',visible='season == 3')
    art.ellipse(-.58,.295,.082,.012,'alpha(wood, 0.15)',1)
    # Foreground grasses, seed heads and seasonal flowers.
    art.draw('lines',1,count=64,samples=5, x='-1.25 + 1.12 * hash(i * 3.12)',
             y='0.34 + 0.17 * hash(i * 7.18)', px='s * 0.008 * wind',
             py='-s * (0.009 + 0.026 * hash(i * 4.7))', width=.0014,
             color='alpha(wood, 0.24)',visible='season != 3')
    art.ellipse('-.95 + 0.72 * hash(i * 4.3)', '0.30 + 0.2 * hash(i * 1.8)',
                .0024,.0018,'mix(leaf_light, sunlight, 0.5)',1,count=46,
                visible='season < 2',samples=8)
    # Right-bank reeds make the water read as a lake and frame the empty space.
    art.polygon([(.63,.52),(.7,.43),(.79,.4),(.9,.38),(1.13,.4),(2,.38),(2,.52)], 'bank',1)
    art.draw('lines',1,count=29,samples=8,x='0.74 + i * 0.013',y='0.48 + 0.018 * sin(i)',
             px='s * (0.015 + 0.012 * wind) * sin(i * 4.3)',
             py='-s * (0.025 + 0.07 * hash(i * 1.7))',width=.0016,
             color='mix(wood, grass_light, 0.25)')
    # Seasonal particles enter/leave off canvas; the cycle is bounded and calm.
    art.draw('group',1,count=30,visible='weather && (season == 0 || season == 2)',
             let=['fall = fract(t / 16 + hash(i * 2.9))'],
             x='-0.77 + 0.5 * hash(i * 1.7) + 0.13 * fall + 0.025 * wind * sin(i + fall * tau)',
             y='-0.24 + fall * 0.65',rotate='i + t * tau / 16',
             opacity='smoothstep(0, 0.1, fall) * (1 - smoothstep(0.85, 1, fall))')
    art.ellipse(0,0,.0035,.0018,'season == 0 ? leaf_light : leaf_mid',2,samples=10)
    art.draw('group',1,count=3,visible='weather && season == 1',
             x='-0.19 + 0.18 * sin(t * tau / 32 + i * 2.1)',
             y='0.23 + 0.05 * sin(t * tau / 16 + i * 2.3)')
    art.ellipse('0.002 + 0.001 * sin(t * tau / 2 + i)',0,.0028,.004,'leaf_light',2,samples=10)
    art.ellipse('-0.002 - 0.001 * sin(t * tau / 2 + i)',0,.0028,.004,'roof',2,samples=10)
    art.ellipse('-.97 + 1.94 * hash(i * 7.3) + 0.025 * sin(t * tau / 16 + i)',
                '-0.6 + 1.2 * fract(t / 16 + hash(i * 2.9))',.0019,.0019,
                'alpha(leaf_light, 0.65)',1,count=72,visible='weather && season == 3',samples=10)
    # Birds share the clear sky, barely moving against the mountains.
    art.draw('lines',1,count=3,samples=12,x='0.10 + i * 0.027 + 0.04 * sin(t * tau / 32)',
             y='-0.23 + i * 0.012',px='(s - 0.5) * 0.015',
             py='abs(s - 0.5) * (0.006 + 0.0015 * sin(t * tau / 4 + i))',
             width=.0008,color='alpha(wood, 0.65)')
    art.write(Path(destination)/'screensafe.toml')


if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv)>1 else Path(__file__).resolve().parents[2]/'packs/seasons')
