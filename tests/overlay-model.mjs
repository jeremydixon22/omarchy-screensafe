import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const model = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL("../OverlayModel.js", import.meta.url), "utf8"), model);
const plain = value => JSON.parse(JSON.stringify(value));
const defaults = plain(model.values({}));
assert.equal(defaults.enabled, 0);
assert.equal(defaults.cpu, 0);
assert.equal(defaults.memory, 0);
assert.equal(defaults.battery, 0);
assert.equal(model.values({ enabled: "1", cpu: true, memory: NaN }).enabled, 0);
assert.equal(model.values(JSON.parse('{"__proto__":{"enabled":1}}')).enabled, 0);
assert.deepEqual(plain(model.values({ position: 100, opacity: -1, size: Infinity })), defaults);
const selected = model.changed({ enabled: 1, position: 4, clock: 0 }, "cpu", 1);
assert.equal(selected.enabled, 1);
assert.equal(selected.clock, 0);
assert.equal(selected.position, 4);
assert.equal(selected.cpu, 1);
const argument = model.argument({ ...selected, hostname: "secret", notification: "private" });
assert.ok(argument.length < 512 && /^[a-z0-9_=.,]+$/.test(argument));
assert.ok(!argument.includes("secret") && !argument.includes("notification"));
let reading = model.reading({ total: 1000, idle: 400, memory: 35 }, null);
assert.equal(reading.cpu, -1);
reading = model.reading({ total: 1100, idle: 425, memory: 36 }, reading);
assert.equal(reading.cpu, 75);
assert.equal(reading.memory, 36);
assert.equal(model.reading({ total: 1, idle: 2, memory: 30 }, null), null);
assert.equal(model.reading({ total: NaN, idle: 0, memory: 30 }, null), null);
assert.equal(model.reading({ total: 1, idle: 0, memory: 101 }, null), null);
assert.equal(model.reading({ total: 1, idle: 0, memory: "30" }, null), null);
console.log("Overlay settings and numeric telemetry validation passed.");
