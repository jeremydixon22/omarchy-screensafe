import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const model = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../PerformanceModel.js', import.meta.url), 'utf8'), model);
const plain = x => JSON.parse(JSON.stringify(x));
assert.deepEqual(plain(model.values({})), { enabled: 0, batteryOnly: 1, maxMiB: 512, videoHardware: 0 });
assert.equal(model.values({ enabled: '1' }).enabled, 0);
assert.equal(model.values(JSON.parse('{"__proto__":{"enabled":1}}')).enabled, 0);
assert.equal(model.values({ maxMiB: Infinity }).maxMiB, 512);
assert.equal(model.values({ maxMiB: -1 }).maxMiB, 512);
assert.deepEqual(plain(model.changed({ enabled: 1 }, 'unknown', 42)), { enabled: 1, batteryOnly: 1, maxMiB: 512, videoHardware: 0 });
assert.equal(model.values({ videoHardware: '1' }).videoHardware, 0);
assert.equal(model.changed({ maxMiB: 1024 }, 'videoHardware', 1).maxMiB, 1024);
assert.equal(model.changed({}, 'videoHardware', 1).videoHardware, 1);
assert.deepEqual(plain(model.playerCommand('/plugin', '/renderer', ['preview','--pack','/pack'], true)),
  ['/usr/bin/python3','/plugin/tools/videos/play_v2.py','--renderer','/renderer','--decoder','vaapi','--device','auto','--','preview','--pack','/pack']);
assert.equal(model.videoStatus('{"screensafeVideo": {"decoder": "hardware"}}\n'), 'hardware');
assert.equal(model.videoStatus('{"screensafeVideo": {"decoder": "software"}}\n{broken'), 'software');
assert.equal(model.videoStatus('{"screensafeVideo": {"decoder": "made-up"}}'), '');
assert.equal(model.videoStatus('arbitrary codec output'), '');
assert.equal(model.changed({}, 'batteryOnly', 0).batteryOnly, 0);
for (const d of model.declarations) if (d.kind === 'choice') assert.equal(d.choices.length, d.values.length);
console.log('Performance defaults and preference validation passed.');
